"""PROFILE the main queries with and without their index; write docs/performance.md.

Usage: python -m scripts.profile_queries
"""

from pathlib import Path

from app.agent.retrieval import TYPED_RELATIONS
from app.db import get_driver
from app.llm import get_embeddings

OUT = Path("docs/performance.md")


def total_db_hits(plan) -> int:
    """Sum the database hits of a profiled plan tree."""
    return plan.get("dbHits", 0) + sum(total_db_hits(child) for child in plan.get("children", []))


def operators(plan) -> list[str]:
    """Operator names of a plan tree, depth first."""
    names = [plan["operatorType"].split("@")[0]]
    for child in plan.get("children", []):
        names += operators(child)
    return names


def profile(driver, query: str, **params) -> dict:
    """Run a query under PROFILE and summarise its plan."""
    with driver.session() as session:
        session.run(query, **params).consume()  # warm-up run, so timings exclude cold caches
        result = session.run("PROFILE " + query, **params)
        rows = len(list(result))
        summary = result.consume()
    plan = summary.profile
    key_ops = [op for op in operators(plan) if op not in ("ProduceResults", "Projection")]
    return {
        "rows": rows,
        "db_hits": total_db_hits(plan),
        "ms": summary.result_available_after + summary.result_consumed_after,
        "operators": " > ".join(dict.fromkeys(key_ops)),
    }


def main() -> None:
    """Entry point."""
    driver = get_driver()
    embedding = get_embeddings().embed_query("condamnation de Nicolas Sarkozy en appel")
    key = "Person:nicolas sarkozy"
    cases = [
        ("Entity by key", "uniqueness constraint",
         "MATCH (e:Entity {key: $key}) RETURN e.name", {"key": key}),
        ("Entity by key", "no index (name property scan)",
         "MATCH (e:Entity) WHERE e.name = $name RETURN e.name", {"name": "Nicolas Sarkozy"}),
        ("Entity name search", "full-text index",
         "CALL db.index.fulltext.queryNodes('entity_names', 'sarkozy') YIELD node "
         "RETURN node.name", {}),
        ("Entity name search", "no index (CONTAINS scan)",
         "MATCH (e:Entity) WHERE toLower(e.name) CONTAINS 'sarkozy' RETURN e.name", {}),
        ("Passage similarity (top 10)", "vector index",
         "CALL db.index.vector.queryNodes('chunk_embedding', 10, $v) YIELD node, score "
         "RETURN node.id, score", {"v": embedding}),
        ("Passage similarity (top 10)", "no index (cosine over every chunk)",
         "MATCH (c:Chunk) WITH c, vector.similarity.cosine(c.embedding, $v) AS score "
         "RETURN c.id, score ORDER BY score DESC LIMIT 10", {"v": embedding}),
        ("Relations of an entity", "key lookup + typed expand",
         f"MATCH (e:Entity {{key: $key}})-[r:{TYPED_RELATIONS}]-(o) RETURN type(r), o.name",
         {"key": key}),
        ("Paths between two entities", "typed relations, at most 4 hops",
         f"MATCH (a:Entity {{key: $a}}), (b:Entity {{key: $b}}) "
         f"MATCH p = allShortestPaths((a)-[:{TYPED_RELATIONS}*..4]-(b)) RETURN length(p)",
         {"a": key, "b": "Person:claude gueant"}),
    ]
    lines = [
        "# Query performance",
        "",
        "Generated by `python -m scripts.profile_queries` (PROFILE on the full graph).",
        "",
        "| Query | Strategy | Rows | DB hits | ms | Plan |",
        "|---|---|---|---|---|---|",
    ]
    for name, strategy, query, params in cases:
        stats = profile(driver, query, **params)
        lines.append(f"| {name} | {strategy} | {stats['rows']} | {stats['db_hits']:,} | "
                     f"{stats['ms']} | {stats['operators']} |")
        print(lines[-1])
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
